#include <iostream>
using namespace std;

int main()
{
    int a , b;
    cout<<"Enter the 1st value:\n";     //'<<' is Insertion Operator
    cin>> a;                            //'>>' is an Extraction Operator
    cout<<"Enter the 2nd value:\n";
    cin>> b;
    cout<< "The sum is "<< a+b;
    return 0;
}
